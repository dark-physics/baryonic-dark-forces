def draw_mX_error(pion_momenta_in_lab_samples, EX_samples, cosX_samples, E_resolution, p_resolution):
  '''
  pion_momenta_in_lab_samples
    tuple of 2 nx4 arrays, four momenta of pi+/pi- samples
    return of transform_restX_to_lab()

  EX_samples
    vector of EX_samples

  cosX_samples
    vector of cosX_samples
  '''

  ## UNPACKING ##
  n = len(EX_samples)
  fourp_plus , fourp_minus = pion_momenta_in_lab_samples

  ## ISOLATING ##
  p_plus = fourp_plus[:,1:]
  p_minus = fourp_minus[:,1:]
  E_plus = fourp_plus[:,0]
  E_minus = fourp_minus[:,0]
  p_plus_x = p_plus[:,0]
  p_plus_y = p_plus[:,1]
  p_plus_z = p_plus[:,2]
  p_minus_x = p_minus[:,0]
  p_minus_y = p_minus[:,1]
  p_minus_z = p_minus[:,2]

  mX_sq_measured = np.zeros(n)
  for i in range(n):
    ## GENERATING SLIGHTLY FUDGED NUMBERS ##
    E_plus_measured = np.random.normal(E_plus[i], E_resolution)
    E_minus_measured = np.random.normal(E_minus[i], E_resolution)
    p_plus_x_measured = np.random.normal(p_plus_x[i], p_resolution)
    p_plus_y_measured = np.random.normal(p_plus_y[i], p_resolution)
    p_plus_z_measured = np.random.normal(p_plus_z[i], p_resolution)
    p_minus_x_measured = np.random.normal(p_minus_x[i], p_resolution)
    p_minus_y_measured = np.random.normal(p_minus_y[i], p_resolution)
    p_minus_z_measured = np.random.normal(p_minus_z[i], p_resolution)

    p_plus_measured = np.array([p_plus_x_measured,p_plus_y_measured,p_plus_z_measured])
    p_minus_measured = np.array([p_minus_x_measured,p_minus_y_measured,p_minus_z_measured])

    mX_sq_measured[i] = (E_plus_measured+E_minus_measured)**2 - np.abs(np.linalg.norm(p_plus_measured + p_minus_measured))**2

  # print(mX_measured)
  plt.hist(mX_sq_measured,bins=30,density=True)
  plt.show()

