def P(s_tot,EX,cosX,params,mX,xq):
  if cosX > 1:
    return 0
  return pm.dsigX_dEX_dcosX(s_tot,EX,cosX,params,mX,xq)

def mcmc_sample_EX_cosX(n,s_tot,params,mX,xq):
  '''
  return
    ndarray : nx2 posterior distribution (EX [GeV], cosX)
  n
    int : number of samples
  s_tot
    float : i genuinely do not fucking know
  params
    ndarray floats : photoproduction model parameters
  mX
    float : X boson mass
  xq
    ndarray floats : quark couplings
  '''

  x_samples = np.zeros((n, 2))

  E_beam = (s_tot - mp**2) / (2 * mp)

  central_E = (E_beam - mX) / 2

  standard_deviation_E = (E_beam-central_E)*0.67
  standard_deviation_cos = 0.01

  # starting point
  x_samples[0,0] = central_E
  x_samples[0,1] = 0.99

  counter = 0
  for i in range(n - 1):
    EX_old = x_samples[i,0]
    cosX_old = x_samples[i,1]

    ## proposal ##
    EX_new = np.random.normal(EX_old,standard_deviation_E)
    cosX_new = np.random.normal(cosX_old,standard_deviation_cos)

    ## accept/reject ##

    A = P(s_tot,EX_new,cosX_new,params,mX,xq) / P(s_tot,EX_old,cosX_old,params,mX,xq)

    if A > 1:
      x_samples[i+1,0] = EX_new
      x_samples[i+1,1] = cosX_new
      counter +=1

    elif A > np.random.uniform(0,1):
      x_samples[i+1,0] = EX_new
      x_samples[i+1,1] = cosX_new
      counter +=1

    else:
      x_samples[i+1,0] = EX_old
      x_samples[i+1,1] = cosX_old

  return x_samples

def sample_pion_four_momenta_in_X(n,mX):
  '''
  return
     P1,P2 : tuple of nd arrays
      corresponding pion four momenta arrays in rest frame of X boson (P2 = -P1)
  n
    int | number of samples
  mX
    float | X boson mass
  '''
  E_pi = mX / 2
  pi_momentum_norm = np.sqrt(E_pi**2-m_pi_charged**2)
  pi_momentum = np.zeros((n,4))

  for i in range(n):
    cos_alpha = np.random.uniform(-1,1)
    sin_alpha = np.sqrt(1 - cos_alpha**2) # ignoring that sin could be pos or neg

    phi = np.random.uniform(0,2*np.pi)

    pi_momentum[i,0] = E_pi #natural units
    pi_momentum[i,1] = sin_alpha * np.cos(phi) * pi_momentum_norm
    pi_momentum[i,2] = sin_alpha * np.sin(phi) * pi_momentum_norm
    pi_momentum[i,3] = cos_alpha * pi_momentum_norm

  return [pi_momentum, pi_momentum*[1,-1,-1,-1]]

def transform_restX_to_lab(EX_samples, cosX_samples, mX, pion_four_momenta_samples_in_X):
  '''
  return
    P1,P2 : tuple of nd arrays
      pi+ , pi- four momenta in lab
  '''

  pi_plus_four_momenta_samples_in_X , pi_minus_four_momenta_samples_in_X = pion_four_momenta_samples_in_X

  assert len(EX_samples) == len(pi_plus_four_momenta_samples_in_X) , "cosX, EX sample size doesnt match pion momenta sample size"

  N = len(EX_samples)

  pi_plus_four_momenta_samples_in_lab = np.zeros((N,4))
  pi_minus_four_momenta_samples_in_lab = np.zeros((N,4))

  ## TRANSFORM MATRICES ##
  for i in range(N):
    gamma = EX_samples[i] / mX
    beta = np.sqrt(1 - 1/gamma**2)

    cX = cosX_samples[i]
    sX = np.sqrt(1 - cX**2)

    Lambda = np.array([
        [gamma, 0,  0, gamma*beta],
        [0,   1,  0,  0],
        [0, 0,  1, 0],
        [beta*gamma, 0,  0, gamma]
    ])
    R = np.array([
        [1, 0,  0, 0],
        [0, cX, 0,  -sX],
        [0, 0,  1, 0],
        [0, sX, 0, cX]
    ])

    pi_plus_four_momenta_samples_in_lab[i] = R@Lambda@pi_plus_four_momenta_samples_in_X[i]
    pi_minus_four_momenta_samples_in_lab[i] = R@Lambda@pi_minus_four_momenta_samples_in_X[i]

  return pi_plus_four_momenta_samples_in_lab, pi_minus_four_momenta_samples_in_lab

